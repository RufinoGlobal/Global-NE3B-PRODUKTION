// Generates the one-time D1 import SQL from NE3-DATEN-NICHT-LOESCHEN.json.
// Uses INSERT ... WHERE NOT EXISTS so re-running can never overwrite newer
// production data that is already in D1.
//
// Usage: node scripts/generate-import-sql.mjs [source.json] [out.sql]
import fs from 'node:fs';

const src = process.argv[2] || 'NE3-DATEN-NICHT-LOESCHEN.json';
const out = process.argv[3] || 'import-data.sql';

const raw = fs.readFileSync(src, 'utf8');
const d = JSON.parse(raw);
if (d.app !== 'GGB-NE3') {
  console.error(`FEHLER: unerwartetes app-Feld: ${d.app}`);
  process.exit(1);
}

const esc = (s) => s.replace(/'/g, "''");
const records = [];
for (const [k, v] of Object.entries(d.lists || {})) records.push(['list', k, v]);
for (const [k, v] of Object.entries(d.belege || {})) records.push(['belege', k, v]);
for (const [k, v] of Object.entries(d.over || {})) records.push(['over', k, v]);
records.push(['meta', 'extra', d.extra || {}]);
records.push(['meta', 'extraAreas', d.extraAreas || []]);

const now = d.savedAt || new Date().toISOString();
let sql = '-- Generated by scripts/generate-import-sql.mjs – idempotent, never overwrites existing rows.\n';
let seq = 0;
for (const [type, key, data] of records) {
  seq++;
  sql += `INSERT INTO records (type, key, data, rev, seq, updated_at) ` +
    `SELECT '${esc(type)}', '${esc(key)}', '${esc(JSON.stringify(data))}', 1, ${seq}, '${esc(now)}' ` +
    `WHERE NOT EXISTS (SELECT 1 FROM records WHERE type = '${esc(type)}' AND key = '${esc(key)}');\n`;
}
fs.writeFileSync(out, sql);
console.log(`OK: ${records.length} Datensätze → ${out}`);
console.log(`   lists=${Object.keys(d.lists || {}).length} belege=${Object.keys(d.belege || {}).length} over=${Object.keys(d.over || {}).length} extra=${Object.keys(d.extra || {}).length} extraAreas=${(d.extraAreas || []).length}`);
